inventory = []

# Множество хранит уникальные найденные предметы
found_items = set()

# Множество хранит пройденные уровни
completed_levels = set()

# ------------------------------------------
# СЛОВАРЬ
# В нём хранятся предметы и их описания
# ------------------------------------------

items = {
    "ключ": "Старый ключ от ворот фермы",
    "морковь": "Вкусная морковка для зайчика",
    "масло": "Масло для починки трактора",
    "колесо": "Новое колесо для трактора",
    "яблоко": "Красное яблоко для коровы",
    "звезда": "Золотая звезда за прохождение испытаний"
}

