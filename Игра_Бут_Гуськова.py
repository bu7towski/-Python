# ------------------------------------------
# ФУНКЦИЯ ПОКАЗА ИНВЕНТАРЯ
# ------------------------------------------

def show_inventory():
    print()
    print("ТВОЙ ИНВЕНТАРЬ:")

    if len(inventory) == 0:
        print("Пока ничего нет. Даже бутерброда!")
    else:
        for item in inventory:
            print("-", item)

    print()

# ------------------------------------------
# ФУНКЦИЯ ДОБАВЛЕНИЯ ПРЕДМЕТА
# ------------------------------------------

def add_item(item):
    if item not in found_items:
        inventory.append(item)
        found_items.add(item)
        print("Ты получил предмет:", item)
        print(items[item])
    else:
        print("Этот предмет уже найден!")

    print()

# ------------------------------------------
# ФУНКЦИЯ ЗАВЕРШЕНИЯ УРОВНЯ
# ------------------------------------------

def finish_level(number):
    completed_levels.add(number)
    print()
    print("Уровень успешно пройден!")
    print("Синий трактор радостно сигналит: БИИИП!")
    print()

