def level_one():

    print("===================================")
    print("УРОВЕНЬ 1:", levels[0])
    print("===================================")

    print("Синий трактор проснулся на поле.")
    print("Но у него пропали инструменты!")
    print("Нужно найти ключ и масло.")
    print()

    print("Перед тобой три места:")
    print("1. Старый сарай")
    print("2. Большой куст")
    print("3. Куча сена")

    key_found = False
    oil_found = False

    while key_found == False or oil_found == False:

        choice = input("Куда поедем? Введи 1, 2 или 3: ")

        if choice == "1":
            print("Ты заехал в старый сарай.")
            print("Под трактором лежит ключ!")
            add_item("ключ")
            key_found = True

        elif choice == "2":
            print("Под кустом сидит сердитая курица!")
            print("Курица кричит: КУДА ПОЕХАЛ?!")
            print("Трактор испугался и дал задний ход.")

        elif choice == "3":
            print("Ты нашёл масло!")
            add_item("масло")
            oil_found = True

        else:
            print("Неправильный выбор!")
            print("Попробуй ещё раз.")

        if key_found == True and oil_found == True:
            print("Отлично! Все предметы найдены!")

    finish_level(1)


